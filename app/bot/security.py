def private_request_reply(text):
    value = text.lower().replace('ё', 'е')
    personal = re.search(r'\b(?:мой|моя|мои|мое|моего|меня|наш|наша|наши|его|ее|чужой|участника)\b', value)
    secret = re.search(r'\b(?:ip(?:шник\w*)?|айпи(?:шник\w*)?|ипшник\w*|парол\w*|токен\w*|секрет\w*)\b', value)
    if personal and secret:
        return 'Я не получаю IP, пароли или токены участников и не могу их узнать. Придумывать их тоже не буду.'
    return None


def computer_action_reply(text):
    value = text.lower().replace('ё', 'е')
    action = re.search(r'\b(?:удали|сотри|уничтожь|сломай|измени|открой|прочитай|запусти|выполни|создай|'
                       r'перезапиши|отформатируй|выключи|перезагрузи|скачай|установи)\b', value)
    target = re.search(r'файл|папк|диск|компьютер|команд|терминал|powershell|\bcmd\b|os\.remove|'
                       r'subprocess|\bexe\b|скрипт|программ|процесс|браузер|сайт|[a-z]:\\', value)
    if action and target:
        return ('У меня нет управления компьютером или доступа к твоим файлам. '
                'Я ничего не запускаю и не меняю. Могу объяснить, как это сделать самому, если нужно.')
    return None


def safe_output(text, secrets=()):
    for value in secrets:
        if value and len(value) > 5:
            text = text.replace(value, '[секрет скрыт]')
    text = re.sub(r'\b(?:mfa\.[A-Za-z0-9_-]{20,}|[A-Za-z0-9_-]{23,28}\.[A-Za-z0-9_-]{6}\.[A-Za-z0-9_-]{25,})\b',
                  '[токен скрыт]', text)
    def address(match):
        try:
            ipaddress.ip_address(match[0])
            return '[IP скрыт]'
        except ValueError:
            return match[0]
    text = re.sub(r'(?<![\w.])(?:\d{1,3}\.){3}\d{1,3}(?![\w.])', address, text)
    return re.sub(r'(?<![\w:])(?=[0-9a-fA-F:]*:[0-9a-fA-F:]*:)[0-9a-fA-F:]+(?![\w:])', address, text)


def assert_no_tools(payload):
    message = payload.get('message', {})
    if message.get('tool_calls') or payload.get('tool_calls'):
        raise RuntimeError('Модель запросила инструмент; выполнение запрещено')
